"""Identificação de vogal ou consoante

Material extraído do notebook 3_EstruturasdeProgramacao.ipynb.
"""

texto = 'c'
if texto == 'a':
  print("É vogal a")
elif texto == 'e':
  print("É vogal e")
elif texto == 'i':
  print("É vogal i")
elif texto == 'o':
  print("É vogal o")
elif texto == 'u':
  print("É vogal u")
else:
  print("É consoante")
